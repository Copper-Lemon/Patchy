"""Regenerate the private symbol header after updating vendored libjxl.

Every libjxl C API name (Jxl*), Brotli global (Brotli*, kBrotli*) and skcms entry point
(skcms_*) gets a patchy_jxl_ prefix, so a system libjxl, Brotli or skcms loaded into the
process never interposes on Patchy's copy or the reverse. Names upstream already #defines
are left alone. Audit the built archive's defined globals after upgrades (llvm-nm or
dumpbin /symbols): nothing outside the jxl:: and hwy:: namespaces may stay unprefixed.
"""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[2]
dest = root / "src/formats/libjxl"

# Brotli globals the pattern below misses: tables without the prefix, and functions whose
# names its macros paste together (FN(BrotliHistogramCombine) for each histogram type).
# Audited with dumpbin /linkermember on patchy_jxl.lib (libjxl 0.12.0, Brotli 1.2.0).
extra = '''AttachPreparedDictionary CreatePreparedDictionary DestroyPreparedDictionary kCmdLut
kStaticDictionaryBuckets kStaticDictionaryHashLengths kStaticDictionaryHashWords kStaticDictionaryWords
_kBrotliContextLookupTable _kBrotliPrefixCodeRanges'''.split()
for stem in ("BrotliClusterHistograms", "BrotliCompareAndPushToQueue", "BrotliHistogramBitCostDistance",
             "BrotliHistogramCombine", "BrotliHistogramReindex", "BrotliHistogramRemap"):
    extra += [stem + kind for kind in ("Literal", "Command", "Distance")]

names = set(extra)
macros = set()
for path in sorted(dest.rglob("*")):
    if path.suffix in (".h", ".c", ".cc"):
        source = path.read_text(encoding="utf-8")
        names.update(re.findall(r"\b(?:Jxl|Brotli|kBrotli|skcms_)[A-Za-z0-9_]*\b", source))
        macros.update(re.findall(r"^\s*#\s*define\s+(\w+)", source, re.M))
names.difference_update(macros)
header = """// Private libjxl 0.12.0, Brotli and skcms symbols.
// Generated by scripts/dev/generate-jxl-symbols.py. Do not edit manually.
#pragma once

"""
header += "".join(f"#define {name} patchy_jxl_{name}\n" for name in sorted(names))
(root / "src/formats/jxl_symbols.hpp").write_text(header, encoding="utf-8", newline="\n")
